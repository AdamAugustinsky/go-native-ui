// useShaders makes the next newLibrary decide again, from fsys, and forget
// the loads recorded so far; the test's cleanup goes back to the embedded
// library.
func useShaders(t *testing.T, fsys fs.FS) {
	t.Helper()
	reset := func(fsys fs.FS) {
		shaderFS, shaderLib = fsys, libState{}
		quadSeen.Store(false)
		backdropSeen.Store(false)
		loadsMu.Lock()
		loads = nil
		loadsMu.Unlock()
	}
	reset(fsys)
	t.Cleanup(func() { reset(metallib.Files) })
}

// shaderFiles is a shader file system holding data as the library, with a
// manifest that records hash as its SHA-256 and source as its sources' hash.
func shaderFiles(data []byte, hash, source string) fstest.MapFS {
	m, _ := json.Marshal(metallib.Manifest{Schema: metallib.Schema, File: "shaders.metallib", Bytes: int64(len(data)), SHA256: hash, SourceSHA256: source})
	return fstest.MapFS{"lib/manifest.json": {Data: m}, "lib/shaders.metallib": {Data: data}}
}

// Each way the embedded library can be unusable ends in the source
// compiled, a working pipeline and the reason in ShaderLoads: absent (the
// supported state before a library is generated), missing, corrupt, stale,
// refused by Metal (bytes that are no library), or the source forced.
func TestShaderLibraryFallsBackToSource(t *testing.T) {
	resetWarm()
	r := newTestRenderer(t)
	junk := []byte("MTLB not a library")
	sources := metallib.SourceHash(quadMSL, backdropMSL)
	empty, _ := json.Marshal(metallib.Manifest{Schema: metallib.Schema})
	missing := shaderFiles(junk, metallib.Hash(junk), sources)
	delete(missing, "lib/shaders.metallib")
	for _, c := range []struct {
		name  string
		fsys  fs.FS
		force bool
		why   string
	}{
		{"absent", fstest.MapFS{"lib/manifest.json": {Data: empty}}, false, "no precompiled library"},
		{"missing", missing, false, "which is missing"},
		{"corrupt", shaderFiles(junk, metallib.Hash([]byte("other bytes")), sources), false, "not the library the manifest names"},
		{"stale", shaderFiles(junk, metallib.Hash(junk), metallib.SourceHash("other", backdropMSL)), false, "stale"},
		{"refused", shaderFiles(junk, metallib.Hash(junk), sources), false, "did not load"},
		{"forced", shaderFiles(junk, metallib.Hash(junk), sources), true, "GNUI_METAL_SOURCE=1"},
	} {
		t.Run(c.name, func(t *testing.T) {
			if c.force {
				t.Setenv("GNUI_METAL_SOURCE", "1")
			}
			useShaders(t, c.fsys)
			p, fail := quadPipeline(objc.F, r.device, &nsErrorOut)
			if fail != buildOK {
				t.Fatalf("quad pipeline failed at step %d: %s", fail, nsErrorText())
			}
			objc.Release(p)
			got := ShaderLoads()
			if len(got) != 1 || got[0].Library != "quad" || got[0].Precompiled || !strings.Contains(got[0].Reason, c.why) {
				t.Fatalf("ShaderLoads() = %+v, want the quad source compiled because %q", got, c.why)
			}
		})
	}
}

// With a real library, the embedded one or the one CI just generated
// (GNUI_TEST_METALLIB_DIR: a directory holding manifest.json and the
// library), both libraries are precompiled and draw what the source draws.
func TestShaderLibraryPrecompiledDrawsTheSame(t *testing.T) {
	fsys := fs.FS(metallib.Files)
	if dir := os.Getenv("GNUI_TEST_METALLIB_DIR"); dir != "" {
		m := fstest.MapFS{}
		for _, f := range []string{"manifest.json", "shaders.metallib"} {
			b, err := os.ReadFile(filepath.Join(dir, f))
			if err != nil {
				t.Fatal(err)
			}
			m["lib/"+f] = &fstest.MapFile{Data: b}
		}
		fsys = m
	}
	b, _ := fs.ReadFile(fsys, "lib/manifest.json")
	if m, ok := metallib.Parse(b); !ok || m.File == "" {
		t.Skip("no precompiled library (generated by tools/metallib in CI)")
	}
	resetWarm()
	scene := func() *DrawList {
		list := &DrawList{}
		list.Add(solid(0, 0, 48, 64, 0xFF0000FF))
		list.Add(solid(10, 10, 40, 30, 0xFFFFFF80))
		card := solid(52, 8, 90, 40, 0x00FF00FF)
		card.Radii, card.Border, card.BorderColor = [4]float32{6, 6, 6, 6}, 2, 0x000000FF
		list.Add(card)
		shadow := solid(14, 40, 44, 56, 0x00000099)
		shadow.Radii, shadow.Soft = [4]float32{4, 4, 4, 4}, 4
		list.Add(shadow)
		list.AddBackdrop(solid(20, 20, 76, 50, 0x808080FF), Backdrop{Sigma: 6, Down: 2, Tint: 0xFFFFFFFF, Mix: 0.3, Saturation: 1.2})
		return list
	}
	const w, h = 96, 64
	useShaders(t, fsys)
	pre := renderList(newTestRenderer(t), w, h, black, scene())
	for _, l := range ShaderLoads() {
		if !l.Precompiled {
			t.Errorf("%s: compiled the source: %s", l.Library, l.Reason)
		}
	}
	if n := len(ShaderLoads()); n != 2 {
		t.Errorf("%d shader loads, want quad and backdrop", n)
	}
	t.Setenv("GNUI_METAL_SOURCE", "1")
	useShaders(t, fsys)
	src := renderList(newTestRenderer(t), w, h, black, scene())
	for y := 0; y < h; y++ {
		for x := 0; x < w; x++ {
			near(t, "precompiled vs source", pre.at(x, y), src.at(x, y), 1)
		}
	}
}

// tools/metallib and provenance read the shader sources out of the Go
// files; what they read is what this package compiles.
func TestShaderSourcesAsToolsReadThem(t *testing.T) {
	quad, backdrop, err := mslsrc.Read(".")
	if err != nil {
		t.Fatal(err)
	}
	if quad != quadMSL || backdrop != backdropMSL {
		t.Fatal("mslsrc.Read does not return quadMSL and backdropMSL")
	}
}
