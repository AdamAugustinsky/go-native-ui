package text

import "unicode/utf8"

//go:generate go run ../tools/genbidi -out bidi_table.go

// The paragraph-direction classes of bidiRanges: the Bidi_Class values that
// UAX #9 rules P2 and P3 look at, the rest folded into bidiOther.
const (
	bidiOther   = iota
	bidiL       // L
	bidiR       // R and AL
	bidiIsolate // LRI, RLI and FSI
	bidiPDI     // PDI
)

// bidiClass is the paragraph-direction class of r (bidiRanges).
func bidiClass(r rune) uint8 {
	if r < 0x80 {
		if r >= 'A' && r <= 'Z' || r >= 'a' && r <= 'z' {
			return bidiL
		}
		return bidiOther
	}
	k := uint32(r)<<3 | 7
	lo, hi := 0, len(bidiRanges)-1
	for lo < hi { // the last start at or below r
		m := (lo + hi + 1) / 2
		if bidiRanges[m] <= k {
			lo = m
		} else {
			hi = m - 1
		}
	}
	return uint8(bidiRanges[lo] & 7)
}

// FirstStrongRTL reports whether the paragraph that b starts with (up to its
// first newline) is right to left by UAX #9 rules P2 and P3: its first
// character of Bidi_Class L, R or AL, skipping the characters between an
// isolate initiator (LRI, RLI, FSI) and its matching PDI (or the end of the
// paragraph), is R or AL. Text without one is left to right. The classes are
// Unicode 17.0's (bidi_table.go, generated by tools/genbidi).
func FirstStrongRTL(b []byte) bool { return paraStrongRTL(b) }

func paraStrongRTL(b []byte) bool {
	depth := 0
	for i := 0; i < len(b); {
		if newlineAt(b, i) > 0 {
			return false
		}
		r, n := utf8.DecodeRune(b[i:])
		i += n
		switch bidiClass(r) {
		case bidiL:
			if depth == 0 {
				return false
			}
		case bidiR:
			if depth == 0 {
				return true
			}
		case bidiIsolate:
			depth++
		case bidiPDI:
			if depth > 0 {
				depth--
			}
		}
	}
	return false
}
