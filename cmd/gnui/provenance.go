package main

import (
	"fmt"
	"io"
	"os/exec"
	"strings"

	"gonativeui/provenance"
)

// cmdProvenance prints the provenance of the framework tree an application
// builds from (docs/design/build-provenance.md): by default the gonativeui
// module directory `go list -m` resolves from the working directory.
func cmdProvenance(args []string, stdout, stderr io.Writer) error {
	fs := newFlagSet("provenance", stderr)
	dir := fs.String("dir", "", "the framework source tree (default: go list -m -f {{.Dir}} gonativeui)")
	asJSON := fs.Bool("json", false, "print the gnui.provenance/v1 JSON")
	if err := parseFlags(fs, args); err != nil {
		return err
	}
	if fs.NArg() > 0 {
		return usageError{fmt.Errorf("unexpected arguments %q", fs.Args())}
	}
	if *dir == "" {
		out, err := exec.Command("go", "list", "-m", "-f", "{{.Dir}}", provenance.Module).Output()
		if err != nil || strings.TrimSpace(string(out)) == "" {
			return fmt.Errorf("resolving the %s module (run from the application's module, or pass -dir): %v", provenance.Module, err)
		}
		*dir = strings.TrimSpace(string(out))
	}
	info, err := provenance.Read(*dir)
	if err != nil {
		return err
	}
	if *asJSON {
		_, err := stdout.Write(info.JSON())
		return err
	}
	f := info.Framework
	dirty := "unknown"
	if f.Dirty != nil {
		dirty = fmt.Sprint(*f.Dirty)
	}
	fmt.Fprintf(stdout, "framework  %s %s (dirty: %s, from %s) at %s\n", f.Module, f.Revision, dirty, f.Source, *dir)
	fmt.Fprintf(stdout, "ghostty    %s, Zig %s, ABI checked by %s, %d built libraries\n", info.Ghostty.Commit, info.Ghostty.ZigVersion, info.Ghostty.ABICheck, len(info.Ghostty.Libraries))
	if s := info.Shaders; s.Artifact == "metallib" {
		fmt.Fprintf(stdout, "shaders    metallib %s (sources %s), %s, %s, generated by %s\n", s.MetallibSHA256, s.SourceSHA256, s.Compiler, s.Target, s.GeneratedBy)
	} else {
		fmt.Fprintln(stdout, "shaders    no precompiled library: the source is compiled at run time")
	}
	fmt.Fprintf(stdout, "go         %s %s/%s\n", info.Go.Version, info.Go.GOOS, info.Go.GOARCH)
	return nil
}
