// Command genbidi generates text/bidi_table.go, the Bidi_Class table that
// text uses for paragraph direction (UAX #9 rules P2 and P3), from the Unicode
// Character Database's DerivedBidiClass.txt.
//
//	go run ./tools/genbidi                      # downloads the file
//	go run ./tools/genbidi -in DerivedBidiClass.txt
//
// Only the classes the paragraph-direction rules look at are kept: strong
// left to right (L), strong right to left (R and AL), the isolate initiators
// (LRI, RLI, FSI) and PDI; every other class is "other". The table is a sorted
// list of range starts, each packed with its class, so a lookup is a binary
// search. Unassigned code points take the file's @missing defaults (Hebrew and
// Arabic blocks right to left, the rest of the code space left to right).
package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"strconv"
	"strings"
)

const version = "17.0.0"

// Packed classes, as in text/bidi.go.
const (
	clsOther = iota
	clsL
	clsR
	clsIsolate
	clsPDI
)

var names = map[string]int{
	"L": clsL, "Left_To_Right": clsL,
	"R": clsR, "Right_To_Left": clsR,
	"AL": clsR, "Arabic_Letter": clsR,
	"LRI": clsIsolate, "Left_To_Right_Isolate": clsIsolate,
	"RLI": clsIsolate, "Right_To_Left_Isolate": clsIsolate,
	"FSI": clsIsolate, "First_Strong_Isolate": clsIsolate,
	"PDI": clsPDI, "Pop_Directional_Isolate": clsPDI,
}

func main() {
	in := flag.String("in", "", "DerivedBidiClass.txt (default: download Unicode "+version+")")
	out := flag.String("out", "text/bidi_table.go", "output file")
	flag.Parse()

	var src []byte
	var err error
	if *in != "" {
		src, err = os.ReadFile(*in)
	} else {
		src, err = download("https://www.unicode.org/Public/" + version + "/ucd/extracted/DerivedBidiClass.txt")
	}
	if err != nil {
		log.Fatal(err)
	}
	if !bytes.Contains(src, []byte("DerivedBidiClass-"+version+".txt")) {
		log.Fatalf("not DerivedBidiClass-%s.txt", version)
	}

	const n = 0x110000
	cls := make([]uint8, n)
	var missing, explicit int
	sc := bufio.NewScanner(bytes.NewReader(src))
	for sc.Scan() {
		line := sc.Text()
		isMissing := strings.HasPrefix(line, "# @missing:")
		if isMissing {
			line = strings.TrimPrefix(line, "# @missing:")
		} else if i := strings.IndexByte(line, '#'); i >= 0 {
			line = line[:i]
		}
		line = strings.TrimSpace(line)
		if line == "" {
			continue
		}
		f := strings.Split(line, ";")
		if len(f) != 2 {
			log.Fatalf("bad line %q", sc.Text())
		}
		lo, hi := parseRange(strings.TrimSpace(f[0]))
		c := names[strings.TrimSpace(f[1])] // other classes are 0
		// @missing lines come first, each overriding the ones before it for
		// its range; the explicit values then override them.
		for r := lo; r <= hi; r++ {
			cls[r] = uint8(c)
		}
		if isMissing {
			missing++
		} else {
			explicit++
		}
	}
	if err := sc.Err(); err != nil {
		log.Fatal(err)
	}
	if missing == 0 || explicit < 1000 {
		log.Fatalf("parsed %d @missing and %d explicit lines", missing, explicit)
	}

	var starts []uint32
	for r := 0; r < n; r++ {
		if r == 0 || cls[r] != cls[r-1] {
			starts = append(starts, uint32(r)<<3|uint32(cls[r]))
		}
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by tools/genbidi from DerivedBidiClass-%s.txt; DO NOT EDIT.\n\n", version)
	b.WriteString("package text\n\n")
	fmt.Fprintf(&b, "// bidiUnicodeVersion is the Unicode version of bidiRanges.\n")
	fmt.Fprintf(&b, "const bidiUnicodeVersion = %q\n\n", version)
	b.WriteString("// bidiRanges are the starts of the ranges of code points of one paragraph-\n")
	b.WriteString("// direction class (bidiOther, bidiL, bidiR, bidiIsolate, bidiPDI), packed as\n")
	b.WriteString("// start<<3 | class and sorted; a range runs to the next start.\n")
	fmt.Fprintf(&b, "var bidiRanges = [%d]uint32{", len(starts))
	for i, s := range starts {
		if i%8 == 0 {
			b.WriteString("\n")
		}
		fmt.Fprintf(&b, "0x%07x, ", s)
	}
	b.WriteString("\n}\n")
	code, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, code, 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("%s: %d ranges", *out, len(starts))
}

func parseRange(s string) (lo, hi int) {
	a, b, ok := strings.Cut(s, "..")
	lo = parseHex(a)
	hi = lo
	if ok {
		hi = parseHex(b)
	}
	if lo > hi || hi >= 0x110000 {
		log.Fatalf("bad range %q", s)
	}
	return lo, hi
}

func parseHex(s string) int {
	v, err := strconv.ParseUint(strings.TrimSpace(s), 16, 32)
	if err != nil {
		log.Fatal(err)
	}
	return int(v)
}

func download(url string) ([]byte, error) {
	resp, err := http.Get(url)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("%s: %s", url, resp.Status)
	}
	return io.ReadAll(resp.Body)
}
